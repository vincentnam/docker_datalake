#!/bin/bash
# Generates the configuration of the access zone (REST API, web GUI, nginx) from conf.env :
#   volumes/configmap_flask_env.yml        environment of the Flask API (no secret)
#   volumes/secret_flask_env.yml           secrets of the Flask API (Keycloak client secret, IdP reader password, session key)
#   volumes/configmap_web_gui_nginx.yml    nginx conf serving the React build
#   volumes/configmap_nginx_proxy.yml      nginx conf of the entry point : / -> web GUI, /api/ -> Flask
#
# Kubernetes counterpart of the access zone sections of the root create_conf.sh (flask/.env, web_gui/.env)
# and of access_zone/nginx/conf.d/default.conf (fixed 10.5.x.x IPs replaced by the Service names).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
CONF_ENV="${CONF_ENV:-$SCRIPT_DIR/../../conf.env}"
VOLUMES_PATH="$SCRIPT_DIR/volumes"

NAMESPACE="datalake"

if [ ! -f "$CONF_ENV" ]; then
  echo "Error: $CONF_ENV not found."
  exit 1
fi
export $(grep -v '^#' "$CONF_ENV" | sed 's/\r$//' | xargs)

for var in FLASK_SECRET KEYCLOAK_CLIENT_SECRET IDP_READER_PASSWORD WEB_GUI_URL KEYCLOAK_PUBLIC_URL KEYCLOAK_REALM; do
  if [ -z "${!var:-}" ]; then
    echo "Set $var in $CONF_ENV."
    exit 1
  fi
done

# Same derivations as the root create_conf.sh
KEYCLOAK_ISSUER="${KEYCLOAK_ISSUER:-${KEYCLOAK_PUBLIC_URL%/}/realms/${KEYCLOAK_REALM}}"
KEYCLOAK_REDIRECT_URI="${WEB_GUI_URL%/}/api/auth/callback"
IDP_READER_PROJECT="service"
# Kubernetes Service names instead of the Compose IPs
OBJECT_STORAGE_BACKEND="swift"
AUTHENTICATION_BACKEND="openstack"
S3_ENDPOINT="http://swift-proxy:8080"

mkdir -p "$VOLUMES_PATH"

# indent <n> : shifts stdin by n spaces, to embed a file in a YAML block scalar
indent() {
  sed "s/^/$(printf '%*s' "$1" '')/"
}

# kv <VAR...> : one '  VAR: "value"' line per variable, value escaped for YAML
kv() {
  local var value
  for var in "$@"; do
    value="${!var:-}"
    value="${value//\\/\\\\}"
    value="${value//\"/\\\"}"
    echo "  $var: \"$value\""
  done
}

####################################
## REST API (Flask)
####################################
cat << EOF > "$VOLUMES_PATH/configmap_flask_env.yml"
# Generated by create_conf.sh from conf.env : edit create_conf.sh, not this file
apiVersion: v1
kind: ConfigMap
metadata:
  name: flask-env
  namespace: $NAMESPACE
  labels:
    app.kubernetes.io/name: flask-app
    app.kubernetes.io/part-of: access-zone
data:
$(kv FEDERATION_ENABLED KEYCLOAK_URL KEYCLOAK_PUBLIC_URL KEYCLOAK_ISSUER KEYCLOAK_REALM KEYCLOAK_CLIENT_ID \
     KEYCLOAK_REDIRECT_URI KEYCLOAK_IDP_ID KEYCLOAK_PROTOCOL_ID FEDERATED_PROJECT FEDERATED_DOMAIN \
     IDP_READER_USER IDP_READER_PROJECT KEYSTONE_URL WEB_GUI_URL JUPYTERHUB_PUBLIC_LOGIN_URL \
     OBJECT_STORAGE_BACKEND AUTHENTICATION_BACKEND S3_ENDPOINT)
EOF

# stringData : plain values, Kubernetes encodes them itself. Holds secrets : never committed (.gitignore)
cat << EOF > "$VOLUMES_PATH/secret_flask_env.yml"
# Generated by create_conf.sh from conf.env : edit create_conf.sh, not this file
apiVersion: v1
kind: Secret
metadata:
  name: flask-env
  namespace: $NAMESPACE
  labels:
    app.kubernetes.io/name: flask-app
    app.kubernetes.io/part-of: access-zone
type: Opaque
stringData:
$(kv KEYCLOAK_CLIENT_SECRET IDP_READER_PASSWORD FLASK_SECRET)
EOF
chmod 600 "$VOLUMES_PATH/secret_flask_env.yml"

####################################
## WEB GUI (nginx serving the React build)
####################################
# quoted heredoc : the $ of nginx are kept as is
WEB_GUI_NGINX_CONF=$(cat << 'EOF'
server {
    listen 8080;
    server_name _;
    root /usr/share/nginx/html;

    location = /nginx-health {
        access_log off;
        return 200 "OK";
    }

    # React Router : an unknown path serves index.html, the application routes it
    location / {
        try_files $uri $uri/ /index.html;
    }

    # hashed files of the build : cached by the browser
    location /static/ {
        expires 1y;
        add_header Cache-Control "public, immutable";
    }
}
EOF
)

cat << EOF > "$VOLUMES_PATH/configmap_web_gui_nginx.yml"
# Generated by create_conf.sh : edit create_conf.sh, not this file
apiVersion: v1
kind: ConfigMap
metadata:
  name: web-gui-nginx
  namespace: $NAMESPACE
  labels:
    app.kubernetes.io/name: web-gui
    app.kubernetes.io/part-of: access-zone
data:
  default.conf: |
$(echo "$WEB_GUI_NGINX_CONF" | indent 4)
EOF

####################################
## NGINX PROXY (entry point of the data lake)
####################################
NGINX_PROXY_CONF=$(cat << 'EOF'
server {
    listen 8080;
    server_name _;  # accepte tout

    # Taille max pour les uploads
    client_max_body_size 500M;

    location = /nginx-health {
        access_log off;
        return 200 "OK";
    }

    # 1. Application web principale (défaut sur /)
    location / {
        proxy_pass         http://web-gui:8080;
        proxy_set_header   Host $host;
        proxy_set_header   X-Real-IP $remote_addr;
        proxy_set_header   X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header   X-Forwarded-Proto $scheme;
        proxy_redirect     off;
    }

    # 2. API Flask → /api/
    location /api/ {
        proxy_pass         http://flask-app:5000/;
        proxy_set_header   Host $host;
        proxy_set_header   X-Real-IP $remote_addr;
        proxy_set_header   X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header   X-Forwarded-Proto $scheme;

        # Réécrit les URLs renvoyées par Flask si besoin
        sub_filter_once off;
        sub_filter 'href="/' 'href="/api/';
        sub_filter 'src="/'  'src="/api/';
    }

    # 3. JupyterHub → /hub/ : ajouté avec la migration de JupyterHub
    #    (nginx refuse de démarrer si le nom d'un upstream n'existe pas)
}
EOF
)

cat << EOF > "$VOLUMES_PATH/configmap_nginx_proxy.yml"
# Generated by create_conf.sh : edit create_conf.sh, not this file
apiVersion: v1
kind: ConfigMap
metadata:
  name: nginx-proxy
  namespace: $NAMESPACE
  labels:
    app.kubernetes.io/name: nginx-proxy
    app.kubernetes.io/part-of: access-zone
data:
  default.conf: |
$(echo "$NGINX_PROXY_CONF" | indent 4)
EOF

echo "Generated :"
echo "  $VOLUMES_PATH/configmap_flask_env.yml"
echo "  $VOLUMES_PATH/secret_flask_env.yml"
echo "  $VOLUMES_PATH/configmap_web_gui_nginx.yml"
echo "  $VOLUMES_PATH/configmap_nginx_proxy.yml"
